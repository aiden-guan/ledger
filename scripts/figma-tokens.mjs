// Turns the variables read from the Figma Design file (design/figma/figma-variables.json)
// into design-tokens.json (W3C design tokens format) and tokens.css.
// Usage: node scripts/figma-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../design/figma/", import.meta.url);
const src = JSON.parse(readFileSync(new URL("figma-variables.json", dir), "utf8"));

const hex = ({ r, g, b }) =>
  "#" + [r, g, b].map((c) => Math.round(c * 255).toString(16).padStart(2, "0")).join("");
const slug = (name) => name.split("/").pop();

const [primitives, semantic] = src.collections;
const pigments = Object.fromEntries(primitives.vars.map((v) => [v.name, hex(v.value)]));

const tokens = { $description: `Read from ${src.source} at ${src.readAt}`, color: {}, space: {}, radius: {}, type: {} };
const css = [`/* Generated by scripts/figma-tokens.mjs from ${src.source} */`, ":root {"];

for (const v of semantic.vars) {
  if (v.type === "COLOR") {
    tokens.color[slug(v.name)] = { $type: "color", $value: pigments[v.alias], $extensions: { figma: { variable: v.name, alias: v.alias } } };
    css.push(`  --${slug(v.name)}: ${pigments[v.alias]};`);
  } else if (v.name.startsWith("space-")) {
    tokens.space[v.name.slice(6)] = { $type: "dimension", $value: `${v.value}px`, $extensions: { figma: { variable: v.name } } };
    css.push(`  --${v.name}: ${v.value}px;`);
  } else {
    tokens.radius.default = { $type: "dimension", $value: `${v.value}px`, $extensions: { figma: { variable: v.name } } };
    css.push(`  --${v.name}: ${v.value}px;`);
  }
}
for (const t of src.textStyles) {
  const name = slug(t.name);
  tokens.type[name] = {
    $type: "typography",
    $value: { fontFamily: t.family, fontWeight: t.weight, fontSize: `${t.size}px`, lineHeight: t.lineHeightPercent / 100 },
    $extensions: { figma: { textStyle: t.name } },
  };
  css.push(`  --type-${name}: ${t.weight} ${t.size}px/${t.lineHeightPercent / 100} "${t.family}";`);
}
css.push("}", "");

writeFileSync(new URL("design-tokens.json", dir), JSON.stringify(tokens, null, 2) + "\n");
writeFileSync(new URL("tokens.css", dir), css.join("\n"));
console.log("wrote design/figma/design-tokens.json and design/figma/tokens.css");
